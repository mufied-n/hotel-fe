test('offers explicit sample staff workspaces while API staff routes stay locked', async ({ page, request }) => {
  await page.goto('/staff/housekeeping')
  await expect(page.getByText('Preview data sample')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Housekeeping board.' })).toBeVisible()
  await expect(page.getByText('6 kamar pada hasil filter.')).toBeVisible()
  await page.goto('/staff/front-desk')
  await expect(page.getByRole('heading', { name: 'Front desk.' })).toBeVisible()
  await page.goto('/staff/finance')
  await expect(page.getByRole('heading', { name: 'Finance.' })).toBeVisible()
  const response = await request.get('/api/bff/staff/housekeeping/rooms')
  expect(response.status()).toBe(503)
  expect(await response.json()).toMatchObject({ data: { code: 'CAPABILITY_DISABLED' } })
  const mutation = await request.post('/api/bff/staff/finance/refunds', { headers: { 'X-Pulang-CSRF': '1' }, data: { booking_id: 'demo', amount_minor: 1, reason: 'sample' } })
  expect(mutation.status()).toBe(503)
  const guestRequest = await request.get('/api/bff/guest/bookings/demo/special-requests')
  expect(guestRequest.status()).toBe(503)
})

