test('keeps booking motion usable with reduced motion and exposes quote feedback', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/booking/results?v=1&check_in=2026-10-03&check_out=2026-10-04&guests=1')
  await expect(page.getByRole('heading', { name: 'Kamar dan paket' })).toBeVisible()
  const reveal = page.locator('.section-reveal').first()
  await expect.poll(() => reveal.evaluate(element => getComputedStyle(element).animationName)).toBe('none')
  await expect.poll(() => page.locator('.button').first().evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')

  const firstCard = page.locator('.room-card').first()
  await firstCard.getByLabel('Varian / tempat tidur').selectOption('deluxe-king-bay')
  await firstCard.getByLabel('Room Only').check()
  await firstCard.getByRole('button', { name: 'Pilih kamar & paket' }).click()
  await expect(firstCard.getByText(/Dipilih: Deluxe King Bay Window/)).toBeVisible()
  const navigation = page.waitForURL(/\/booking\/guest$/)
  await page.getByRole('button', { name: 'Lanjut' }).click()
  await expect(page.getByText('Menyiapkan total pilihan…')).toBeVisible()
  await navigation
})
